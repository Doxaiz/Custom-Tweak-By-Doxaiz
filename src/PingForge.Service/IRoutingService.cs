using PingForge.Service.Protocol;

namespace PingForge.Service;

/// <summary>
/// Команды «Сервера маршрутизации» (задача B): найти реальные шлюзы и измерить пути до игрового
/// сервера через каждый узел.
///
/// Зачем отдельный порт, а не методы у LiveEngineOperations напрямую: сама служба не должна
/// зависеть от сетевого слоя — «мозги» службы остаются проверяемыми без Windows, а реализацию
/// прикручивает композиционный корень (Service.Host). Без порта команды честно отвечают
/// «слой маршрутизации не подключён», а не делают вид, что всё хорошо.
///
/// Правило, которое держит этот порт: discovery — только чтение (можно и в канале просмотра),
/// измерение — меняющая команда (временные /32), только основной канал и права администратора
/// у клиента.
/// </summary>
public interface IRoutingService
{
    /// <summary>Список узлов-кандидатов: шлюзы активных адаптеров и сохранённые вручную. Ничего не меняет.</summary>
    Task<EngineOperationResult> DiscoverAsync(CancellationToken ct = default);

    /// <summary>
    /// Сравнение путей до адреса текущей игры: прямой замер, затем через каждый узел с временным /32
    /// и гарантированным снятием. Побеждает только измеренный выигрыш — иначе «ничего не меняем».
    /// </summary>
    Task<EngineOperationResult> MeasureAsync(CancellationToken ct = default);
}
