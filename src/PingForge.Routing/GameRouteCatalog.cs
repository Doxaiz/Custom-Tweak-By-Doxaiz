    /// <summary>Бесплатен ли способ (по имени из <see cref="PathKinds"/>).</summary>
    public static bool IsFreePath(string kindRu) => FreePathKindsRu.Contains(kindRu);

    /// <summary>Сколько способов из справочника не требуют денег.</summary>
    public static int FreePathCount => PathKinds.Count(p => IsFreePath(p.KindRu));

    /// <summary>Число прописью для коротких фраз: «ровно четыре».</summary>
    private static string CountWord(int count) => count switch
    {
        0 => "ни одного",
        1 => "один",
        2 => "два",
        3 => "три",
        4 => "четыре",
        5 => "пять",
        6 => "шесть",
        7 => "семь",
        _ => count.ToString()
    };

