namespace PingForge.Routing;

/// <summary>
/// Игра и её официальные серверные регионы: то, куда программа пробует построить путь.
///
/// Честно про адреса: игры не публикуют список адресов дата-центров, а матчмейкер выдаёт сервер на
/// конкретный матч. Поэтому здесь регионы (их игры публикуют) и типовые порты там, где они официально
/// описаны. Конкретный адрес сервера программа узнаёт из живого потока игры, а не из этого списка.
/// </summary>
public sealed record GameRouteTarget(
    string GameRu,
    string ProcessName,
    bool IsFreeToPlay,
    IReadOnlyList<string> RegionsRu,
    IReadOnlyList<string> PublishedPortsRu,
    string NoteRu);

/// <summary>Бесплатный публичный DNS-резолвер: это не «маршрут до игры», а выбор более быстрого входного узла.</summary>
public sealed record PublicDnsRoute(string ProviderRu, string PrimaryIp, string SecondaryIp, string NoteRu);

