namespace PingForge.Core.Models;

/// <summary>
/// Слова о пороге «настоящего выигрыша». Порог складывается из минимальной планки и разброса серий
/// обоих путей — но разброс может быть неизмерен, а неизмеренное приравнивать к нулю нельзя: тогда
/// «выигрыш больше шума» превращается в утверждение о шуме, которого никто не видел.
/// </summary>
public static class ThresholdNotes
{
    /// <summary>Минимальная планка выигрыша, ниже которой маршрут не трогаем.</summary>
    public const double MinimalGainMs = 0.5;

    /// <summary>
    /// Неизмеренный разброс назван словами. Числа при этом не выдумываются: порог остаётся по
    /// минимальной планке, и человек читает, что шум в нём не учтён.
    /// </summary>
    public const string NoiseUnmeasuredRu =
        "Разброс одного из путей не измерен — порог взят по минимальной планке, и шум в нём не учтён.";
}
